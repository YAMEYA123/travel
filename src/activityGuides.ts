export function getActivityGuide(item:Activity):Guide {
  const specific=guides[item.id]
  const base=specific||defaults[item.kind]
  const tips=specific?.tips||[
    item.important?'这是关键节点，请为排队或交通变化预留缓冲。':'按当天实际体力灵活控制停留时间。',
    item.booked?'票务或订单已确认，出发前保存离线凭证。':'如涉及票务或停车，请以现场与官方信息为准。'
  ]
  return {...base,tips:openingNotes[item.id]?[openingNotes[item.id],...tips]:tips}
}
